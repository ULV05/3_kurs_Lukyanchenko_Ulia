# Простой конвертер валют
print("КОНВЕРТЕР ВАЛЮТ (Рубли в Доллары)")

# Курс доллара (можно изменить)
usd_rate = 97.5

# Запрашиваем сумму в рублях
rub = float(input("Введите сумму в рублях: "))

# Конвертируем в доллары
usd = rub / usd_rate

# Выводим результат с округлением до 2 знаков
print(f"{rub} рублей = {usd:.2f} долларов (по курсу {usd_rate})")
