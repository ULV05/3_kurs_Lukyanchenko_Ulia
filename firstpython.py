# Запрашиваем имя пользователя
name = input("Введите ваше имя: ")

# Запрашиваем возраст и преобразуем в целое число
age = int(input("Сколько вам лет? "))

# Вычисляем, сколько лет осталось до 100
years_to_100 = 100 - age

# Выводим результат
print(f"Привет, {name}! Через {years_to_100} лет вам исполнится 100 лет.")  
